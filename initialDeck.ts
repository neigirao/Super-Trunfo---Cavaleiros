// Helper function to create a card
const createCard = (
  id: number,
  name: string,
  elementType: ElementType,
  reactivity: number,
  atomicMass: number,
  radioactivity: number,
  conductivity: number,
  hardness: number,
  isSuperTrunfo = false
): CardData => ({
  id: isSuperTrunfo ? 'ST' : id.toString(),
  name: name,
  imageUrl: `https://picsum.photos/seed/${name.replace(/ /g, '')}/400/600`,
  element: elementType,
  attributes: {
    [Attribute.Reatividade]: reactivity,
    [Attribute.MassaAtomica]: atomicMass,
    [Attribute.Radioatividade]: radioactivity,
    [Attribute.Condutividade]: conductivity,
    [Attribute.Dureza]: hardness,
  },
  isSuperTrunfo,
});

